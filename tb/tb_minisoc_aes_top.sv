// ==============================================================================
// Testbench: tb_minisoc_aes_top
// Description: Self-checking Block Testbench for Shared Memory (minisoc_memory)
//              and AES-128 Multi-Block Engine (minisoc_aes_top) - Semana 6:
//              1. Memory ownership arbitration (MEM_SEL_AES=0 external load/read,
//                 MEM_SEL_AES=1 exclusive AES in-place processing).
//              2. ECB Mode (3'b000): Encrypt & Decrypt for 1, 2, and 256 blocks
//                 compared against Python golden reference vectors.
//              3. CBC Mode (3'b001): Encrypt & Decrypt for 1, 2, and 256 blocks
//                 compared against Python golden reference vectors.
//              4. CTR Mode (3'b101): Encrypt & Decrypt for 1, 2, and 256 blocks
//                 compared against Python golden reference vectors.
//              5. Invalid configuration detection (NUM_BLOCKS = 0, 257;
//                 reserved/unimplemented MODE = 010, 011, 100, 110, 111):
//                 verifies ERROR=1, BUSY=0, DONE=0, BLOCKS_DONE=0, memory
//                 unmodified, and clean recovery on subsequent valid START.
// ==============================================================================

module tb_minisoc_aes_top;

    // --------------------------------------------------------------------------
    // Golden Reference Vectors (auto-generated by scripts/gen_aes_ref_vectors.py)
    // --------------------------------------------------------------------------
    `include "minisoc_aes_ref_vectors.svh"

    localparam logic [2:0] MODE_ECB  = 3'b000;
    localparam logic [2:0] MODE_CBC  = 3'b001;
    localparam logic [2:0] MODE_PCBC = 3'b010;
    localparam logic [2:0] MODE_CFB  = 3'b011;
    localparam logic [2:0] MODE_OFB  = 3'b100;
    localparam logic [2:0] MODE_CTR  = 3'b101;
    localparam logic [2:0] MODE_RSV6 = 3'b110;
    localparam logic [2:0] MODE_RSV7 = 3'b111;

    // --------------------------------------------------------------------------
    // Clocks & Reset
    // - sys_clk (AES domain): 500 MHz (T = 2.0 ns)
    // - mem_clk (External MEMORY DATA domain): 200 MHz (T = 5.0 ns)
    // --------------------------------------------------------------------------
    logic sys_clk;
    logic mem_clk;
    logic rst_n;

    initial begin
        sys_clk = 1'b0;
        forever #1.0 sys_clk = ~sys_clk;
    end

    initial begin
        mem_clk = 1'b0;
        forever #2.5 mem_clk = ~mem_clk;
    end

    // --------------------------------------------------------------------------
    // DUT Interconnect Signals
    // --------------------------------------------------------------------------
    logic         mem_sel_aes;

    // External MEMORY DATA Interface
    logic         mem_i_wr_en;
    logic [9:0]   mem_i_addr;
    logic [31:0]  mem_i_data;
    logic [31:0]  mem_o_data;

    // AES Engine Control & Configuration
    logic         aes_start;
    logic         cfg_decrypt;
    logic [2:0]   cfg_mode;
    logic [31:0]  cfg_num_blocks;
    logic [127:0] cfg_key;
    logic [127:0] cfg_iv;
    logic [63:0]  cfg_counter;

    // AES Status Outputs
    logic         aes_busy;
    logic         aes_done;
    logic         aes_error;
    logic [8:0]   aes_blocks_done;

    // AES <-> Shared Memory Internal Port
    logic         aes_mem_wr_en;
    logic [9:0]   aes_mem_addr;
    logic [31:0]  aes_mem_wdata;
    logic [31:0]  aes_mem_rdata;

    // --------------------------------------------------------------------------
    // DUT Instantiations: minisoc_memory & minisoc_aes_top
    // --------------------------------------------------------------------------
    minisoc_memory u_dut_mem (
        .mem_sel_aes_i (mem_sel_aes),
        .ext_clk_i     (mem_clk),
        .ext_wr_en_i   (mem_i_wr_en),
        .ext_addr_i    (mem_i_addr),
        .ext_wdata_i   (mem_i_data),
        .ext_rdata_o   (mem_o_data),
        .aes_clk_i     (sys_clk),
        .aes_wr_en_i   (aes_mem_wr_en),
        .aes_addr_i    (aes_mem_addr),
        .aes_wdata_i   (aes_mem_wdata),
        .aes_rdata_o   (aes_mem_rdata)
    );

    minisoc_aes_top u_dut_aes (
        .clk_i            (sys_clk),
        .rst_ni           (rst_n),
        .start_i          (aes_start),
        .cfg_decrypt_i    (cfg_decrypt),
        .cfg_mode_i       (cfg_mode),
        .cfg_num_blocks_i (cfg_num_blocks),
        .cfg_key_i        (cfg_key),
        .cfg_iv_i         (cfg_iv),
        .cfg_counter_i    (cfg_counter),
        .busy_o           (aes_busy),
        .done_o           (aes_done),
        .error_o          (aes_error),
        .blocks_done_o    (aes_blocks_done),
        .mem_wr_en_o      (aes_mem_wr_en),
        .mem_addr_o       (aes_mem_addr),
        .mem_wdata_o      (aes_mem_wdata),
        .mem_rdata_i      (aes_mem_rdata)
    );

    // --------------------------------------------------------------------------
    // Helper Tasks (Lint-clean without null statements)
    // --------------------------------------------------------------------------
    int   err_cnt;
    int   pass_cnt;
    logic tb_tick;

    task automatic wait_sys_cycles(input int n);
        repeat (n) @(posedge sys_clk) tb_tick = ~tb_tick;
    endtask

    task automatic wait_mem_cycles(input int n);
        repeat (n) @(posedge mem_clk) tb_tick = ~tb_tick;
    endtask

    // External MEMORY DATA single 32-bit word write (requires mem_sel_aes = 0)
    task automatic ext_write_word(
        input logic [9:0]  addr,
        input logic [31:0] data
    );
        @(posedge mem_clk) begin
            mem_i_wr_en <= 1'b1;
            mem_i_addr  <= addr;
            mem_i_data  <= data;
        end
        @(posedge mem_clk) begin
            mem_i_wr_en <= 1'b0;
        end
    endtask

    // External MEMORY DATA single 32-bit word read (requires mem_sel_aes = 0)
    task automatic ext_read_word(
        input  logic [9:0]  addr,
        output logic [31:0] data
    );
        @(posedge mem_clk) begin
            mem_i_wr_en <= 1'b0;
            mem_i_addr  <= addr;
        end
        // 1st edge: SRAM latches address and updates sram_rdata_q
        wait_mem_cycles(1);
        // 2nd edge: sample stable sram_rdata_q
        @(posedge mem_clk) data = mem_o_data;
    endtask

    // External MEMORY DATA 128-bit block write (4 words: base+0 .. base+3)
    task automatic ext_write_block(
        input int           blk_idx,
        input logic [127:0] blk_data
    );
        logic [9:0] base_addr;
        base_addr = 10'(blk_idx * 4);
        ext_write_word(base_addr + 10'd0, blk_data[127:96]);
        ext_write_word(base_addr + 10'd1, blk_data[95:64]);
        ext_write_word(base_addr + 10'd2, blk_data[63:32]);
        ext_write_word(base_addr + 10'd3, blk_data[31:0]);
    endtask

    // External MEMORY DATA 128-bit block read (4 words: base+0 .. base+3)
    task automatic ext_read_block(
        input  int           blk_idx,
        output logic [127:0] blk_data
    );
        logic [9:0]  base_addr;
        logic [31:0] w0, w1, w2, w3;
        base_addr = 10'(blk_idx * 4);
        ext_read_word(base_addr + 10'd0, w0);
        ext_read_word(base_addr + 10'd1, w1);
        ext_read_word(base_addr + 10'd2, w2);
        ext_read_word(base_addr + 10'd3, w3);
        blk_data = {w0, w1, w2, w3};
    endtask

    // Trigger AES operation and wait for completion (DONE or ERROR)
    task automatic trigger_and_wait_aes(
        input logic [2:0]  mode,
        input logic        decrypt,
        input logic [31:0] n_blocks
    );
        int timeout_guard;
        timeout_guard = 0;

        @(posedge sys_clk) begin
            cfg_mode       <= mode;
            cfg_decrypt    <= decrypt;
            cfg_num_blocks <= n_blocks;
            cfg_key        <= REF_KEY;
            cfg_iv         <= REF_IV;
            cfg_counter    <= REF_CTR;
            aes_start      <= 1'b1;
        end
        @(posedge sys_clk) begin
            aes_start <= 1'b0;
        end

        // Wait 1 cycle for FSM to enter ST_VALIDATE
        wait_sys_cycles(1);

        // Poll until busy_o drops back to 0
        while ((aes_busy == 1'b1) && (timeout_guard < 20000)) begin
            wait_sys_cycles(1);
            timeout_guard++;
        end

        if (timeout_guard >= 20000) begin
            $display("  [FAIL] Timeout waiting for AES completion (mode=%03b, n=%0d)!",
                     mode, n_blocks);
            err_cnt++;
        end
    endtask

    // Run complete Encrypt + Decrypt in-place verification for a given mode and N
    task automatic run_mode_batch_test(
        input string       mode_name,
        input logic [2:0]  mode_code,
        input int          n_blocks
    );
        logic [127:0] got_blk;
        logic [127:0] exp_ct;
        int           blk_mismatches;

        // ------------------------------------------------------------------
        // Step A: Load N plaintext blocks via external MEMORY DATA interface
        // ------------------------------------------------------------------
        mem_sel_aes = 1'b0;
        wait_mem_cycles(1);
        for (int i = 0; i < n_blocks; i++) begin
            ext_write_block(i, REF_PT_BLOCKS[i]);
        end

        // ------------------------------------------------------------------
        // Step B: Hand memory to AES (MEM_SEL_AES=1) and run ENCRYPT
        // ------------------------------------------------------------------
        mem_sel_aes = 1'b1;
        wait_sys_cycles(2);
        trigger_and_wait_aes(mode_code, 1'b0, 32'(n_blocks));

        if ((aes_done !== 1'b1) || (aes_error !== 1'b0) || (aes_busy !== 1'b0) ||
            (aes_blocks_done !== 9'(n_blocks))) begin
            $display("  [FAIL] %s Encrypt (N=%0d) status: done=%0b err=%0b busy=%0b blks=%0d",
                     mode_name, n_blocks, aes_done, aes_error, aes_busy, aes_blocks_done);
            err_cnt++;
        end else begin
            pass_cnt++;
        end

        // Verify DONE remains sticky across idle cycles
        wait_sys_cycles(4);
        if (aes_done !== 1'b1) begin
            $display("  [FAIL] %s Encrypt (N=%0d): DONE did not remain sticky!",
                     mode_name, n_blocks);
            err_cnt++;
        end else begin
            pass_cnt++;
        end

        // Return memory to external interface (MEM_SEL_AES=0) and verify CT blocks
        mem_sel_aes    = 1'b0;
        blk_mismatches = 0;
        wait_mem_cycles(1);

        for (int i = 0; i < n_blocks; i++) begin
            ext_read_block(i, got_blk);
            case (mode_code)
                MODE_ECB: exp_ct = REF_ECB_CT_BLOCKS[i];
                MODE_CBC: exp_ct = REF_CBC_CT_BLOCKS[i];
                MODE_CTR: exp_ct = REF_CTR_CT_BLOCKS[i];
                default:  exp_ct = 128'd0;
            endcase
            if (got_blk !== exp_ct) begin
                if (blk_mismatches < 4) begin
                    $display("  [FAIL] %s Encrypt (N=%0d) blk[%0d]: got %032h, exp %032h",
                             mode_name, n_blocks, i, got_blk, exp_ct);
                end
                blk_mismatches++;
                err_cnt++;
            end
        end

        if (blk_mismatches == 0) begin
            $display("  [PASS] %-3s Encrypt (%3d block(s)): %3d/%3d blocks match reference (BLOCKS_DONE=%0d)",
                     mode_name, n_blocks, n_blocks, n_blocks, aes_blocks_done);
            pass_cnt++;
        end

        // ------------------------------------------------------------------
        // Step C: Hand memory back to AES (MEM_SEL_AES=1) and run DECRYPT
        //         in-place directly on the ciphertext currently in SRAM
        // ------------------------------------------------------------------
        mem_sel_aes = 1'b1;
        wait_sys_cycles(2);
        trigger_and_wait_aes(mode_code, 1'b1, 32'(n_blocks));

        if ((aes_done !== 1'b1) || (aes_error !== 1'b0) || (aes_busy !== 1'b0) ||
            (aes_blocks_done !== 9'(n_blocks))) begin
            $display("  [FAIL] %s Decrypt (N=%0d) status: done=%0b err=%0b busy=%0b blks=%0d",
                     mode_name, n_blocks, aes_done, aes_error, aes_busy, aes_blocks_done);
            err_cnt++;
        end else begin
            pass_cnt++;
        end

        // Return memory to external interface (MEM_SEL_AES=0) and verify recovered PT
        mem_sel_aes    = 1'b0;
        blk_mismatches = 0;
        wait_mem_cycles(1);

        for (int i = 0; i < n_blocks; i++) begin
            ext_read_block(i, got_blk);
            if (got_blk !== REF_PT_BLOCKS[i]) begin
                if (blk_mismatches < 4) begin
                    $display("  [FAIL] %s Decrypt (N=%0d) blk[%0d]: got %032h, exp %032h",
                             mode_name, n_blocks, i, got_blk, REF_PT_BLOCKS[i]);
                end
                blk_mismatches++;
                err_cnt++;
            end
        end

        if (blk_mismatches == 0) begin
            $display("  [PASS] %-3s Decrypt (%3d block(s)): %3d/%3d blocks recovered in-place (BLOCKS_DONE=%0d)",
                     mode_name, n_blocks, n_blocks, n_blocks, aes_blocks_done);
            pass_cnt++;
        end
    endtask

    // Verify invalid configuration raises ERROR=1 and does not modify memory
    task automatic check_invalid_config(
        input string       label,
        input logic [2:0]  bad_mode,
        input logic [31:0] bad_num_blocks
    );
        mem_sel_aes = 1'b1;
        wait_sys_cycles(2);
        trigger_and_wait_aes(bad_mode, 1'b0, bad_num_blocks);

        if ((aes_error !== 1'b1) || (aes_busy !== 1'b0) ||
            (aes_done !== 1'b0) || (aes_blocks_done !== 9'd0)) begin
            $display("  [FAIL] %s: expected err=1 busy=0 done=0 blks=0, got err=%0b busy=%0b done=%0b blks=%0d",
                     label, aes_error, aes_busy, aes_done, aes_blocks_done);
            err_cnt++;
        end else begin
            $display("  [PASS] %s -> ERROR=1, BUSY=0, DONE=0, BLOCKS_DONE=0", label);
            pass_cnt++;
        end
    endtask

    // --------------------------------------------------------------------------
    // Main Verification Sequence
    // --------------------------------------------------------------------------
    localparam logic [127:0] SENTINEL_BLK = 128'hCAFEBABE_DEADBEEF_01234567_89ABCDEF;
    logic [127:0]            chk_blk;

    initial begin
        err_cnt        = 0;
        pass_cnt       = 0;
        tb_tick        = 1'b0;
        rst_n          = 1'b0;
        mem_sel_aes    = 1'b0;
        mem_i_wr_en    = 1'b0;
        mem_i_addr     = 10'd0;
        mem_i_data     = 32'd0;
        aes_start      = 1'b0;
        cfg_decrypt    = 1'b0;
        cfg_mode       = MODE_ECB;
        cfg_num_blocks = 32'd1;
        cfg_key        = REF_KEY;
        cfg_iv         = REF_IV;
        cfg_counter    = REF_CTR;

        wait_sys_cycles(5);
        rst_n = 1'b1;
        wait_sys_cycles(5);

        $display("========================================================================");
        $display("   MiniSoC AES - Semana 6 Testbench (AES Engine & Shared SRAM 1024x32)  ");
        $display("========================================================================");

        // ======================================================================
        // TEST 1: Shared Memory Ownership & Isolation (Sec. 7.2)
        // ======================================================================
        $display("\n[TEST 1] Shared Memory Ownership & Arbitrator Isolation:");
        mem_sel_aes = 1'b0;
        wait_mem_cycles(1);
        ext_write_block(0, SENTINEL_BLK);

        // Switch ownership to AES (MEM_SEL_AES=1) and attempt external overwrite
        mem_sel_aes = 1'b1;
        wait_mem_cycles(1);
        ext_write_block(0, 128'hFFFFFFFF_FFFFFFFF_FFFFFFFF_FFFFFFFF);

        // Return ownership to external port and confirm sentinel is intact
        mem_sel_aes = 1'b0;
        wait_mem_cycles(1);
        ext_read_block(0, chk_blk);
        if (chk_blk !== SENTINEL_BLK) begin
            $display("  [FAIL] Memory ownership isolation: external write leaked while MEM_SEL_AES=1!");
            err_cnt++;
        end else begin
            $display("  [PASS] Memory ownership isolation verified (external writes blocked when MEM_SEL_AES=1)");
            pass_cnt++;
        end

        // ======================================================================
        // TEST 2: ECB Mode (3'b000) - 1, 2, and 256 Blocks (Encrypt & Decrypt)
        // ======================================================================
        $display("\n[TEST 2] ECB Mode (3'b000) - 1, 2, and 256 Blocks:");
        run_mode_batch_test("ECB", MODE_ECB, 1);
        run_mode_batch_test("ECB", MODE_ECB, 2);
        run_mode_batch_test("ECB", MODE_ECB, 256);

        // ======================================================================
        // TEST 3: CBC Mode (3'b001) - 1, 2, and 256 Blocks (Encrypt & Decrypt)
        // ======================================================================
        $display("\n[TEST 3] CBC Mode (3'b001) - 1, 2, and 256 Blocks:");
        run_mode_batch_test("CBC", MODE_CBC, 1);
        run_mode_batch_test("CBC", MODE_CBC, 2);
        run_mode_batch_test("CBC", MODE_CBC, 256);

        // ======================================================================
        // TEST 4: CTR Mode (3'b101) - 1, 2, and 256 Blocks (Encrypt & Decrypt)
        // ======================================================================
        $display("\n[TEST 4] CTR Mode (3'b101) - 1, 2, and 256 Blocks:");
        run_mode_batch_test("CTR", MODE_CTR, 1);
        run_mode_batch_test("CTR", MODE_CTR, 2);
        run_mode_batch_test("CTR", MODE_CTR, 256);

        // ======================================================================
        // TEST 5: Invalid Configuration Detection (ERROR=1 & Memory Unmodified)
        // ======================================================================
        $display("\n[TEST 5] Invalid Configuration Detection (NUM_BLOCKS & MODE):");

        // Write sentinel block at address 0..3 before invalid start attempts
        mem_sel_aes = 1'b0;
        wait_mem_cycles(1);
        ext_write_block(0, SENTINEL_BLK);

        check_invalid_config("NUM_BLOCKS = 0   (underflow)", MODE_ECB,  32'd0);
        check_invalid_config("NUM_BLOCKS = 257 (overflow) ", MODE_CBC,  32'd257);
        check_invalid_config("NUM_BLOCKS = 32'hFFFF_FFFF  ", MODE_CTR,  32'hFFFF_FFFF);
        check_invalid_config("MODE = 3'b110 (reserved)    ", MODE_RSV6, 32'd1);
        check_invalid_config("MODE = 3'b111 (reserved)    ", MODE_RSV7, 32'd4);
        check_invalid_config("MODE = 3'b010 (PCBC, W10)   ", MODE_PCBC, 32'd1);
        check_invalid_config("MODE = 3'b011 (CFB,  W10)   ", MODE_CFB,  32'd1);
        check_invalid_config("MODE = 3'b100 (OFB,  W10)   ", MODE_OFB,  32'd1);

        // Verify SRAM block 0 was not modified by any aborted operation
        mem_sel_aes = 1'b0;
        wait_mem_cycles(1);
        ext_read_block(0, chk_blk);
        if (chk_blk !== SENTINEL_BLK) begin
            $display("  [FAIL] SRAM modified during invalid configuration handling! got %032h", chk_blk);
            err_cnt++;
        end else begin
            $display("  [PASS] SRAM block 0 preserved intact across all invalid configurations");
            pass_cnt++;
        end

        // Verify recovery: valid 1-block ECB operation clears ERROR and succeeds
        $display("\n[TEST 6] Recovery After ERROR on Next Valid START:");
        run_mode_batch_test("ECB", MODE_ECB, 1);

        // ======================================================================
        // Final Summary
        // ======================================================================
        $display("\n========================================================================");
        if (err_cnt == 0) begin
            $display("   OVERALL RESULT: PASS (0 errors, %0d checks passed)", pass_cnt);
            $display("   - Shared SRAM 1024x32 ownership & in-place R/W verified");
            $display("   - ECB, CBC, CTR (1, 2, 256 blocks) Encrypt & Decrypt match Python reference");
            $display("   - Invalid NUM_BLOCKS & MODE flagged with ERROR=1 and 0 memory corruption");
        end else begin
            $display("   OVERALL RESULT: FAIL (%0d errors, %0d checks passed)", err_cnt, pass_cnt);
        end
        $display("========================================================================");

        wait_sys_cycles(5);
        $finish;
    end

    initial begin
        $fsdbDumpfile("waves.fsdb");
        $fsdbDumpvars(0, tb_minisoc_aes_top);
    end

endmodule
