// ==============================================================================
// Module: minisoc_pll_mock
// Description: MiniSoC AES Integration PLL Mock Model (Block Guide Sec. 4.1)
//              - Reference clock: 2 GHz (clk_i).
//              - Dividers selected by pll_div_sel_i:
//                  2'b00 -> /1 (2.000 GHz)
//                  2'b01 -> /2 (1.000 GHz)
//                  2'b10 -> /4 (500 MHz)
//                  2'b11 -> /8 (250 MHz)
//              - When disabled (pll_en_i = 0): locked_o = 0 and sys_clk_o = 0.
//              - After enable: waits a pseudo-random number of clk_i cycles
//                generated by an 8-bit maximal-length LFSR (16..79 + 2 cycles),
//                then asserts locked_o = 1 and releases glitch-free sys_clk_o.
//              - Integration/verification RTL model (LIM-PLL-01), not a physical
//                PLL macro.
// ==============================================================================

module minisoc_pll_mock #(
    parameter logic [7:0] LOCK_MIN_CYCLES = 8'd16,
    parameter logic [7:0] LFSR_SEED       = 8'hA5
) (
    input  logic       clk_i,
    input  logic       rst_ni,
    input  logic       pll_en_i,
    input  logic [1:0] pll_div_sel_i,
    output logic       sys_clk_o,
    output logic       locked_o
);

    // --------------------------------------------------------------------------
    // Internal Registers
    // --------------------------------------------------------------------------
    logic [7:0] lfsr_q;
    logic       acquiring_q;
    logic       locked_q;
    logic [1:0] div_sel_q;
    logic [7:0] lock_cnt_q;
    logic [7:0] lock_target_q;
    logic [2:0] div_cnt_q;

    // --------------------------------------------------------------------------
    // Glitch-Free Clock Gate Enable (negedge clk_i for /1 path)
    // --------------------------------------------------------------------------
    logic pll_run;
    logic clk_en_neg_q;

    assign pll_run = pll_en_i && locked_q && (pll_div_sel_i == div_sel_q);

    always_ff @(negedge clk_i or negedge rst_ni) begin
        if (!rst_ni) begin
            clk_en_neg_q <= 1'b0;
        end else begin
            clk_en_neg_q <= pll_run;
        end
    end

    // --------------------------------------------------------------------------
    // Free-Running 8-bit Maximal-Length LFSR (x^8 + x^6 + x^5 + x^4 + 1)
    // Provides pseudo-random lock acquisition latency on each enable event.
    // --------------------------------------------------------------------------
    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni) begin
            lfsr_q <= LFSR_SEED;
        end else begin
            lfsr_q <= {lfsr_q[6:0], lfsr_q[7] ^ lfsr_q[5] ^ lfsr_q[4] ^ lfsr_q[3]};
        end
    end

    // --------------------------------------------------------------------------
    // Lock Acquisition FSM & Clock Divider Counter
    // --------------------------------------------------------------------------
    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni) begin
            acquiring_q   <= 1'b0;
            locked_q      <= 1'b0;
            div_sel_q     <= 2'b00;
            lock_cnt_q    <= 8'd0;
            lock_target_q <= LOCK_MIN_CYCLES;
            div_cnt_q     <= 3'd0;
        end else if (!pll_en_i) begin
            // Disabled: deassert lock and keep divider stopped
            acquiring_q <= 1'b0;
            locked_q    <= 1'b0;
            lock_cnt_q  <= 8'd0;
            div_cnt_q   <= 3'd0;
            if (!clk_en_neg_q) begin
                div_sel_q <= pll_div_sel_i;
            end
        end else if (locked_q) begin
            // Locked state: if divisor changes on the fly, drop lock & re-acquire
            if (pll_div_sel_i != div_sel_q) begin
                locked_q    <= 1'b0;
                acquiring_q <= 1'b0;
                lock_cnt_q  <= 8'd0;
                div_cnt_q   <= 3'd0;
            end else begin
                div_cnt_q <= div_cnt_q + 3'd1;
            end
        end else if (acquiring_q) begin
            // Counting pseudo-random lock acquisition cycles
            div_cnt_q <= 3'd0;
            if (pll_div_sel_i != div_sel_q) begin
                div_sel_q     <= pll_div_sel_i;
                lock_cnt_q    <= 8'd0;
                lock_target_q <= LOCK_MIN_CYCLES + {2'b00, lfsr_q[5:0]};
            end else if (lock_cnt_q >= lock_target_q) begin
                locked_q    <= 1'b1;
                acquiring_q <= 1'b0;
            end else begin
                lock_cnt_q <= lock_cnt_q + 8'd1;
            end
        end else begin
            // Start new lock acquisition once previous clock gate is safely closed
            div_cnt_q <= 3'd0;
            if (!clk_en_neg_q) begin
                div_sel_q     <= pll_div_sel_i;
                lock_cnt_q    <= 8'd0;
                lock_target_q <= LOCK_MIN_CYCLES + {2'b00, lfsr_q[5:0]};
                acquiring_q   <= 1'b1;
            end
        end
    end

    // --------------------------------------------------------------------------
    // Divided & Gated System Clock Multiplexer
    // --------------------------------------------------------------------------
    always_comb begin
        case (div_sel_q)
            2'b00:   sys_clk_o = clk_i & clk_en_neg_q; // /1 -> 2.000 GHz
            2'b01:   sys_clk_o = div_cnt_q[0];         // /2 -> 1.000 GHz
            2'b10:   sys_clk_o = div_cnt_q[1];         // /4 -> 500 MHz
            2'b11:   sys_clk_o = div_cnt_q[2];         // /8 -> 250 MHz
            default: sys_clk_o = 1'b0;
        endcase
    end

    assign locked_o = locked_q;

endmodule
